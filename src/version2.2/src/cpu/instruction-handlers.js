import { OPCODE } from '../constants.js';
import { ControlUnit } from './control-unit.js';
import { ALU } from './alu.js';

/**
 * Hardware-Accurate Instruction Execution Handlers - Version 2.2
 *
 * Coordinates execution through true hardware datapath components:
 * - ControlUnit: Generates control wire signals (RegWrite, ALUSrc, MemRead, MemToReg, ALUOp, SetCC).
 * - ALU: Computes arithmetic results and condition codes.
 * - RegisterFile: Dual read ports and gated write-enable port.
 * - Latches: Internal CPU registers (MAR, MDR, PC, PSR).
 */

/**
 * Handles ADD instruction (Opcode 0b0001).
 *
 * Micro-architectural Flow:
 * 1. ControlUnit asserts signals: RegWrite=1, ALUSrc=IMM/REG, MemRead=0, MemToReg=0, ALUOp='ADD', SetCC=1.
 * 2. ID: RegisterFile Port A reads SR1; Port B reads SR2 (if reg mode).
 * 3. EX: ALUSrc MUX selects between Port B and sign-extended imm5; ALU computes addition.
 * 4. MEM: Idle.
 * 5. WB: MemToReg MUX routes ALU_Out to RegisterFile Write Port with RegWrite=ENABLED.
 */
export function handleAdd(vm, decoded) {
  // 1. Control Unit generates control wire signals
  const control = ControlUnit.generateSignals(decoded);

  // 2. ID Stage: Read operands from Register File
  const sr1Val = vm.regFile.readPortA(decoded.sr1);
  const sr2Val = decoded.immFlag ? 0 : vm.regFile.readPortB(decoded.sr2);

  // 3. EX Stage: Multiplexer selects ALU Input B based on ALUSrc control line
  const aluInputB = control.ALUSrc === 'IMM' ? decoded.imm5 : sr2Val;
  const aluOutput = ALU.compute(sr1Val, aluInputB, control.ALUOp);

  // 4. MEM Stage: Idle (MemRead=0, MemWrite=0)

  // 5. WB Stage: MemToReg MUX selects ALU Output; latches into Register File
  const writeData = control.MemToReg ? vm.latches.MDR : aluOutput.result;
  const writeRecord = vm.regFile.write(decoded.dr, writeData, control.RegWrite);

  // WB Stage: PSR latches condition codes generated by ALU
  if (control.SetCC) {
    vm.latches.latchPSR(aluOutput.flags.psrFlag);
  }

  const mode = decoded.immFlag ? 'IMMEDIATE' : 'REGISTER';
  const immStr = decoded.imm5 >= 0 ? `+${decoded.imm5}` : `${decoded.imm5}`;
  const aluSrcDesc = decoded.immFlag
    ? `ALUSrc MUX <= SEXT5 Imm5 (${immStr})`
    : `ALUSrc MUX <= RegFile Port B (R${decoded.sr2} = ${sr2Val})`;

  const hardwareEvents = [
    `[ID Stage]  Control Unit: RegWrite=1, ALUSrc=${control.ALUSrc}, MemRead=0, MemToReg=0, ALUOp=${control.ALUOp}`,
    `[ID Stage]  Register File: Read Port A <= R${decoded.sr1} (${sr1Val})`,
    decoded.immFlag
      ? `[ID Stage]  Sign-Extension Unit (SEXT5): Imm5 <= ${immStr}`
      : `[ID Stage]  Register File: Read Port B <= R${decoded.sr2} (${sr2Val})`,
    `[EX Stage]  ${aluSrcDesc}`,
    `[EX Stage]  ALU Execution: ${sr1Val} ${control.ALUOp} ${aluInputB} = ${aluOutput.result} (Flags: N=${aluOutput.flags.negative ? 1 : 0}, Z=${aluOutput.flags.zero ? 1 : 0}, P=${aluOutput.flags.positive ? 1 : 0})`,
    `[MEM Stage] Memory Bus: IDLE (MemRead=0, MemWrite=0)`,
    `[WB Stage]  MemToReg MUX <= ALU_Out (${writeData})`,
    `[WB Stage]  Register File: Write Port R${decoded.dr} <= ${writeData} (RegWrite: ENABLED)`,
    `[WB Stage]  PSR Latch <= 0b${vm.latches.PSR.toString(2).padStart(3, '0')} (Updated from ALU flags)`,
  ];

  return {
    mode,
    dr: decoded.dr,
    sr1: decoded.sr1,
    sr1Val,
    sr2: decoded.sr2,
    sr2Val,
    imm5: decoded.imm5,
    result: aluOutput.result,
    controlSignals: control,
    aluOutput,
    writeRecord,
    hardwareEvents,
  };
}

/**
 * Handles LD instruction (Opcode 0b0010).
 *
 * Micro-architectural Flow:
 * 1. ControlUnit asserts signals: RegWrite=1, ALUSrc=IMM, MemRead=1, MemToReg=1, ALUOp='ADD', SetCC=1.
 * 2. ID: SEXT9 sign-extends PCoffset9.
 * 3. EX: Address adder computes Effective Address = PC + Offset.
 * 4. MEM: Latches MAR <= Effective Address, strobes MemRead, latches MDR <= RAM[MAR].
 * 5. WB: MemToReg MUX routes MDR to RegisterFile Write Port with RegWrite=ENABLED.
 */
export function handleLd(vm, decoded) {
  // 1. Control Unit generates control wire signals
  const control = ControlUnit.generateSignals(decoded);

  // 2. ID Stage: Sign-extension of 9-bit PC-relative offset
  const offsetStr = decoded.pcOffset9 >= 0 ? `+${decoded.pcOffset9}` : `${decoded.pcOffset9}`;

  // 3. EX Stage: Address Adder computes Effective Address = PC + Offset
  const currentPc = vm.latches.PC;
  const addressCalc = ALU.compute(currentPc, decoded.pcOffset9, control.ALUOp);
  const effectiveAddress = addressCalc.result;

  // 4. MEM Stage: Latch MAR and strobe MemRead to read word into MDR
  vm.latches.latchMAR(effectiveAddress);
  const loadedValue = vm.latches.latchMDR(vm.mem[vm.latches.MAR]);

  // 5. WB Stage: MemToReg MUX routes MDR data to Register File Write Port
  const writeData = control.MemToReg ? vm.latches.MDR : effectiveAddress;
  const writeRecord = vm.regFile.write(decoded.dr, writeData, control.RegWrite);

  // WB Stage: Evaluate condition flags for loaded value and update PSR
  const flags = ALU.evaluateFlags(writeData);
  if (control.SetCC) {
    vm.latches.latchPSR(flags.psrFlag);
  }

  const hardwareEvents = [
    `[ID Stage]  Control Unit: RegWrite=1, ALUSrc=IMM, MemRead=1, MemToReg=1, ALUOp=${control.ALUOp}`,
    `[ID Stage]  Sign-Extension Unit (SEXT9): PCoffset9 <= ${offsetStr}`,
    `[EX Stage]  Address Adder: PC (${currentPc}) + Offset (${offsetStr}) -> Effective Address: ${effectiveAddress}`,
    `[MEM Stage] Memory Address Register (MAR) <= ${effectiveAddress} (Address Bus)`,
    `[MEM Stage] Memory Data Register (MDR) <= ${loadedValue} (Read from RAM[${effectiveAddress}], MemRead: ENABLED)`,
    `[WB Stage]  MemToReg MUX <= MDR (${writeData})`,
    `[WB Stage]  Register File: Write Port R${decoded.dr} <= ${writeData} (RegWrite: ENABLED)`,
    `[WB Stage]  PSR Latch <= 0b${vm.latches.PSR.toString(2).padStart(3, '0')} (Updated from loaded value flags)`,
  ];

  return {
    dr: decoded.dr,
    pcOffset9: decoded.pcOffset9,
    effectiveAddress,
    loadedValue,
    controlSignals: control,
    writeRecord,
    hardwareEvents,
  };
}

/**
 * Dispatch table mapping opcodes to their specific handler functions.
 */
export const INSTRUCTION_DISPATCH_TABLE = {
  [OPCODE.ADD]: handleAdd,
  [OPCODE.LD]:  handleLd,
};
